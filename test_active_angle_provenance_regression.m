function result = test_active_angle_provenance_regression()
%TEST_ACTIVE_ANGLE_PROVENANCE_REGRESSION Retain observed RAE through events.

frame = struct('t_sec', 5, 'active_xyz', [1000; 2000; 300], ...
    'active_rae', [2500; 123.4; -2.5], 'active_R', eye(3), ...
    'active_t', 4.75, 'target_ids', 11, 'active_src', 1, ...
    'active_ae_only', [40; 5], 'active_ae_only_t', 4.8, ...
    'active_ae_only_ids', 12, 'active_ae_only_src', 1, ...
    'passive_ang', zeros(2, 0), 'passive_t', zeros(1, 0), ...
    'passive_ids', zeros(1, 0), 'passive_src', zeros(1, 0));
cfg = struct('processing_framework', 'joint_2d3d', ...
    'async_active_time_mode', 'frame', 'async_same_time_tolerance_s', 1e-9, ...
    'async_microbatch_dt_s', 0.005, 'passive_bearing_enabled', true, ...
    'passive_bearing_update_on_pure', true, 'async_passive_count_miss', false, ...
    'sigma_az_deg', 0.08, 'sigma_el_deg', 0.06, ...
    'sigma_passive_az_deg', 0.05, 'sigma_passive_el_deg', 0.04);

[~, ~, ~, ~, ~, ~, meta] = build_async_measurement_events(frame, cfg);
assert(numel(meta) == 2, ...
    'Separated RAE and AE-only timestamps must form two asynchronous events.');
q = find([meta.n_active] == 1, 1);
assert(~isempty(q) && max(abs(meta(q).active_rae(:, 1) - frame.active_rae)) < 1e-12, ...
    'Observed/condensed RAE must be retained instead of reconstructed from XYZ.');
assert(abs(meta(q).active_t(1) - frame.active_t) < 1e-12, ...
    'Original active measurement time must survive frame-mode event grouping.');

result = struct('passed', true, 'retained_rae', meta(q).active_rae, ...
    'retained_time', meta(q).active_t);
fprintf('主动角度来源回归通过: 凝聚后RAE及原始量测时刻已保留到异步事件。\n');
end
