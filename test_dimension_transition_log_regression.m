function result = test_dimension_transition_log_regression()
%TEST_DIMENSION_TRANSITION_LOG_REGRESSION Committed switch audit semantics.

cfg = struct('joint_3d_upgrade_M', 2, 'joint_3d_upgrade_N', 3, ...
    'joint_up_consecutive', 1, 'joint_down_consecutive', 3, ...
    'joint_radial_sigma_warn_m', 6000, ...
    'joint_radial_sigma_drop_m', 12000, ...
    'joint_range_age_warn_s', 5, 'joint_range_age_drop_s', 15, ...
    'joint_angle95_max_deg', 1, 'joint_switch_gate_2d', 9.2103);

manager_log = [transition(1001, 10, '3d_warn', '2d_shadow', ...
        '3d_quality_degraded'), ...
    transition(1001, 11, '3d_warn', '3d_warn', ...
        '3d_degradation_blocked_2d_not_ready'), ...
    transition(1001, 20, '2d_to_3d', '3d', ...
        '2d_to_3d_2of3_confirmed')];
transactions = cell(3, 1);
transactions{1} = companion(1001, 2, 7, 4, 2, 13000, 16, true, false, 10);
transactions{2} = companion(1001, 3, 7, 4, 2, 13000, 16, false, false, NaN);
transactions{3} = companion(1001, 3, 7, 4, 2, 5000, 4, true, true, 20);
output_map = [map_record(1001, 7, 3, 3), map_record(1001, 4, 2, 1001)];

log = build_track_dimension_transition_log( ...
    manager_log, transactions, [10; 11; 20], output_map, cfg);
assert(numel(log) == 2, ...
    'Only committed 3D->2D and 2D->3D transactions may be exported.');
assert(strcmp(log(1).direction, '3D->2D') && ...
    strcmp(log(2).direction, '2D->3D'), ...
    'Committed dimension switch directions are incorrect.');
assert(log(1).public_3d_track_id == 3 && log(1).public_2d_track_id == 1001, ...
    'The report must resolve both public branch IDs for a downgrade.');
assert(log(2).active_evidence_hits == 2 && ...
    log(2).required_active_hits == 2 && log(2).required_active_window == 3, ...
    'The upgrade row must retain its M/N evidence.');
assert(log(1).radial_sigma_m == 13000 && log(1).range_age_s == 16, ...
    'The downgrade row must retain its numeric quality evidence.');

result = struct('passed', true, 'n_records', numel(log), ...
    'directions', {{log.direction}});
fprintf('升降维事务日志回归通过: 仅保留2条已提交切换，阻断事件已排除。\n');
end

function item = transition(id, t, from, to, reason)
item = struct('id', id, 't_sec', t, 'from', from, 'to', to, 'reason', reason);
end

function item = companion(logical_id, dim, branch3, branch2, hits, ...
        radial_sigma, range_age, consistent, recover3d, commit_t)
quality = struct('radial_sigma_m', radial_sigma, 'range_age_s', range_age, ...
    'angle95_deg', 0.4, 'switch_nis', 2.1, 'valid2d', true, ...
    'recover3d', recover3d, 'switch_consistent', consistent);
item = struct('logical_id', logical_id, 'active_output_dim', dim, ...
    'branch_3d_id', branch3, 'branch_2d_id', branch2, ...
    'external_3d_id', branch3, 'local_2d_id', branch2, ...
    'active_evidence_count', hits, 'active_evidence_window', 3, ...
    'external_fresh', true, 'last_valid_range_t', 5, ...
    'switch_commit_t', commit_t, 'quality', quality);
end

function item = map_record(internal_id, branch_id, dim, output_id)
item = struct('internal_logical_id', internal_id, ...
    'internal_logical_ids', internal_id, 'branch_id', branch_id, ...
    'output_dim', dim, 'output_id', output_id, ...
    'first_output_event', 1, 'last_output_event', 3, ...
    'first_output_t', 1, 'last_output_t', 20, 'n_output_points', 3);
end
